"""
train_model.py - Synthetic dataset, Random Forest training, evaluation,
saving/loading, prediction and a simple explanation of each prediction.

IMPORTANT: the training data here is SYNTHETIC (generated by a program).
The scores below measure how well the model learned the synthetic pattern.
They do NOT prove accuracy on real students.

Run with:  python train_model.py
"""

import json
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import sklearn
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import (
    accuracy_score,
    classification_report,
    confusion_matrix,
    f1_score,
    precision_score,
    recall_score,
)
from sklearn.model_selection import StratifiedKFold, cross_val_score, train_test_split

# ----------------------------------------------------------------------
# File locations and settings
# ----------------------------------------------------------------------
BASE_DIR = Path(__file__).resolve().parent
DATA_PATH = BASE_DIR / "data" / "synthetic_training_data.csv"
MODEL_PATH = BASE_DIR / "ml_model" / "weak_topic_model.joblib"
METRICS_PATH = BASE_DIR / "ml_model" / "metrics.json"

FEATURES = [
    "previous_score",
    "latest_score",
    "num_attempts",
    "days_since_last_practice",
]
FEATURE_LABELS = {
    "previous_score": "Previous score",
    "latest_score": "Latest score",
    "num_attempts": "Number of attempts",
    "days_since_last_practice": "Days since last practice",
}
TARGET = "needs_practice"          # 1 = Needs Practice, 0 = On Track
LABEL_NAMES = {0: "On Track", 1: "Needs Practice"}
RANDOM_STATE = 42                  # fixed seed so results can be reproduced


# ----------------------------------------------------------------------
# 1. Synthetic dataset
# ----------------------------------------------------------------------
def generate_synthetic_data(n_samples=3000, seed=RANDOM_STATE):
    """
    Create a synthetic dataset. Each row is one student-topic situation.

    How it is made (so the label is NOT a simple formula of the columns):
      - Every row has a hidden 'true mastery' value that is never saved.
      - The scores are NOISY measurements of that hidden mastery.
      - Forgetting over time lowers the effective mastery.
      - The label comes from the hidden effective mastery plus random noise.
    So the model must learn a pattern from imperfect clues, like real data.
    """
    rng = np.random.default_rng(seed)

    num_attempts = rng.integers(1, 16, size=n_samples)
    days = np.clip(rng.exponential(scale=7, size=n_samples), 0, 60).round().astype(int)

    base = rng.beta(2.2, 2.0, size=n_samples)
    mastery = np.clip(base + 0.01 * (num_attempts - 6), 0.02, 0.98)

    previous_score = np.clip(mastery * 100 - 4 + rng.normal(0, 12, n_samples), 0, 100)
    latest_score = np.clip(mastery * 100 + rng.normal(0, 12, n_samples), 0, 100)

    effective = mastery - 0.004 * days + rng.normal(0, 0.06, n_samples)
    needs_practice = (effective < 0.50).astype(int)

    return pd.DataFrame({
        "previous_score": previous_score.round(1),
        "latest_score": latest_score.round(1),
        "num_attempts": num_attempts,
        "days_since_last_practice": days,
        TARGET: needs_practice,
    })


# ----------------------------------------------------------------------
# 2. Training and evaluation
# ----------------------------------------------------------------------
def train_and_save():
    """Generate data, train, evaluate on held-out data, save everything."""
    DATA_PATH.parent.mkdir(exist_ok=True)
    MODEL_PATH.parent.mkdir(exist_ok=True)

    df = generate_synthetic_data()
    df.to_csv(DATA_PATH, index=False)

    X = df[FEATURES]
    y = df[TARGET]

    # Split FIRST. The test set is never used for training or tuning.
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.2, stratify=y, random_state=RANDOM_STATE
    )

    model = RandomForestClassifier(
        n_estimators=200,
        max_depth=6,            # limited depth reduces overfitting
        min_samples_leaf=5,
        class_weight="balanced",
        random_state=RANDOM_STATE,
        n_jobs=1,
    )

    # 5-fold cross-validation on the TRAINING data only
    cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=RANDOM_STATE)
    cv_f1 = cross_val_score(model, X_train, y_train, cv=cv, scoring="f1")

    # Final training on the training set
    model.fit(X_train, y_train)

    # Evaluation on the untouched test set
    y_pred = model.predict(X_test)
    train_accuracy = accuracy_score(y_train, model.predict(X_train))

    metrics = {
        "data_type": "SYNTHETIC (generated by a program, not real students)",
        "total_rows": int(len(df)),
        "train_rows": int(len(X_train)),
        "test_rows": int(len(X_test)),
        "class_counts_all": {
            LABEL_NAMES[0]: int((y == 0).sum()),
            LABEL_NAMES[1]: int((y == 1).sum()),
        },
        "accuracy": round(accuracy_score(y_test, y_pred), 4),
        "precision": round(precision_score(y_test, y_pred, zero_division=0), 4),
        "recall": round(recall_score(y_test, y_pred, zero_division=0), 4),
        "f1_score": round(f1_score(y_test, y_pred, zero_division=0), 4),
        "train_accuracy": round(train_accuracy, 4),
        "cv_f1_mean": round(float(cv_f1.mean()), 4),
        "cv_f1_std": round(float(cv_f1.std()), 4),
        # rows = actual [On Track, Needs Practice], columns = predicted
        "confusion_matrix": confusion_matrix(y_test, y_pred, labels=[0, 1]).tolist(),
        "classification_report": classification_report(
            y_test, y_pred, target_names=[LABEL_NAMES[0], LABEL_NAMES[1]],
            output_dict=True, zero_division=0,
        ),
        "feature_importance": {
            f: round(float(v), 4) for f, v in zip(FEATURES, model.feature_importances_)
        },
        "positive_class": "Needs Practice (precision/recall/F1 are for this class)",
        "sklearn_version": sklearn.__version__,
    }

    # Reference values = typical "On Track" student, computed from TRAINING data only.
    # They are used later to explain each prediction.
    reference_values = X_train[y_train == 0].median().to_dict()

    bundle = {
        "model": model,
        "features": FEATURES,
        "reference_values": reference_values,
        "label_names": LABEL_NAMES,
        "trained_on": "synthetic data",
        "sklearn_version": sklearn.__version__,
    }
    joblib.dump(bundle, MODEL_PATH)

    with open(METRICS_PATH, "w", encoding="utf-8") as f:
        json.dump(metrics, f, indent=2)

    return metrics


# ----------------------------------------------------------------------
# 3. Loading and prediction (used by the app pages later)
# ----------------------------------------------------------------------
def load_model():
    """Load the saved model bundle."""
    if not MODEL_PATH.exists():
        raise FileNotFoundError(
            "Model file not found. Run 'python train_model.py' once to train it."
        )
    return joblib.load(MODEL_PATH)


def load_metrics():
    """Load the saved evaluation metrics (used by the Model Evaluation page)."""
    if not METRICS_PATH.exists():
        raise FileNotFoundError(
            "Metrics file not found. Run 'python train_model.py' once to create it."
        )
    with open(METRICS_PATH, encoding="utf-8") as f:
        return json.load(f)


def _validate(previous_score, latest_score, num_attempts, days_since_last_practice):
    for name, value in [("previous_score", previous_score), ("latest_score", latest_score)]:
        if not 0 <= value <= 100:
            raise ValueError(f"{name} must be between 0 and 100")
    if num_attempts < 1:
        raise ValueError("num_attempts must be at least 1")
    if days_since_last_practice < 0:
        raise ValueError("days_since_last_practice cannot be negative")


def _prob_needs_practice(model, row_df):
    index = list(model.classes_).index(1)
    return float(model.predict_proba(row_df)[0][index])


def predict_topic(bundle, previous_score, latest_score, num_attempts, days_since_last_practice):
    """
    Predict 'Needs Practice' or 'On Track' for one topic and explain why.

    Explanation method: for each feature, we replace it with the value of a
    typical On-Track student and see how much the probability changes.
      positive effect -> this feature pushes toward 'Needs Practice'
      negative effect -> this feature pushes toward 'On Track'
    """
    _validate(previous_score, latest_score, num_attempts, days_since_last_practice)

    model = bundle["model"]
    row = pd.DataFrame([{
        "previous_score": previous_score,
        "latest_score": latest_score,
        "num_attempts": num_attempts,
        "days_since_last_practice": days_since_last_practice,
    }])[FEATURES]

    p_needs = _prob_needs_practice(model, row)
    label = LABEL_NAMES[1] if p_needs >= 0.5 else LABEL_NAMES[0]

    factors = []
    for feature in FEATURES:
        changed = row.copy()
        changed[feature] = bundle["reference_values"][feature]
        effect = p_needs - _prob_needs_practice(model, changed)

        if abs(effect) < 0.02:
            meaning = "has little effect on the prediction"
        elif effect > 0:
            meaning = "pushes the prediction toward Needs Practice"
        else:
            meaning = "pushes the prediction toward On Track"

        factors.append({
            "feature": FEATURE_LABELS[feature],
            "value": float(row[feature].iloc[0]),
            "effect": round(effect, 3),
            "meaning": meaning,
        })

    factors.sort(key=lambda item: abs(item["effect"]), reverse=True)

    return {
        "label": label,
        "probability_needs_practice": round(p_needs, 3),
        "confidence": round(max(p_needs, 1 - p_needs), 3),
        "factors": factors,
    }


# ----------------------------------------------------------------------
# Run this file directly to train and test
# ----------------------------------------------------------------------
if __name__ == "__main__":
    print("Training the model on SYNTHETIC data...\n")
    m = train_and_save()

    print(f"Rows: {m['total_rows']} (train {m['train_rows']}, test {m['test_rows']})")
    print(f"Class counts: {m['class_counts_all']}\n")

    print("Held-out TEST set results (class: Needs Practice)")
    print(f"  Accuracy : {m['accuracy']:.3f}")
    print(f"  Precision: {m['precision']:.3f}")
    print(f"  Recall   : {m['recall']:.3f}")
    print(f"  F1-score : {m['f1_score']:.3f}")
    print(f"  5-fold CV F1 on training data: {m['cv_f1_mean']:.3f} (+/- {m['cv_f1_std']:.3f})")
    print(f"  Training accuracy (for overfitting check): {m['train_accuracy']:.3f}\n")

    cm = m["confusion_matrix"]
    print("Confusion matrix (rows = actual, columns = predicted)")
    print("                     Pred On Track   Pred Needs Practice")
    print(f"  Actual On Track        {cm[0][0]:>5}            {cm[0][1]:>5}")
    print(f"  Actual Needs Practice  {cm[1][0]:>5}            {cm[1][1]:>5}\n")

    print("Feature importance:")
    for name, value in sorted(m["feature_importance"].items(), key=lambda kv: -kv[1]):
        print(f"  {FEATURE_LABELS[name]:<26} {value:.3f}")

    print(f"\nSaved model  : {MODEL_PATH}")
    print(f"Saved metrics: {METRICS_PATH}")
    print(f"Saved dataset: {DATA_PATH}")

    # Reload the saved model and test predictions
    bundle = load_model()
    examples = {
        "Weak student": dict(previous_score=35, latest_score=40, num_attempts=3,
                             days_since_last_practice=14),
        "Strong student": dict(previous_score=75, latest_score=90, num_attempts=8,
                               days_since_last_practice=2),
    }
    print("\nExample predictions (loaded from the saved file):")
    for title, values in examples.items():
        result = predict_topic(bundle, **values)
        print(f"\n  {title}: {result['label']} "
              f"(probability of Needs Practice = {result['probability_needs_practice']})")
        for factor in result["factors"]:
            print(f"    - {factor['feature']} = {factor['value']:g}: {factor['meaning']}")

    assert predict_topic(bundle, **examples["Weak student"])["label"] == "Needs Practice"
    assert predict_topic(bundle, **examples["Strong student"])["label"] == "On Track"
    print("\nAll Stage 3 checks passed.")