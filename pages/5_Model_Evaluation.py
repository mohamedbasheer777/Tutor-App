import pandas as pd
import plotly.express as px
import streamlit as st

import ui
from train_model import (DATA_PATH, FEATURE_LABELS, load_metrics, predict_topic,
                         train_and_save)

student_id = ui.setup_page("Model Evaluation", "🧪")
ui.hero("Model Evaluation", "How the weak-topic model was trained and tested")

bundle = ui.get_model()
try:
    metrics = load_metrics()
except FileNotFoundError:
    st.error("Metrics file not found.")
    if st.button("Train the model now"):
        train_and_save()
        st.rerun()
    st.stop()

st.warning(
    "**These results use SYNTHETIC data.** The data was generated by a program. "
    "The scores below show how well the model learned that synthetic pattern. "
    "They do **not** prove accuracy on real students. Real accuracy can only be "
    "measured after collecting real student data."
)

st.subheader("Held-out test-set results")
st.caption(f"Positive class: Needs Practice. Test rows: {metrics['test_rows']} "
           f"(never used for training).")
c1, c2, c3, c4 = st.columns(4)
with c1:
    ui.card("Accuracy", f"{metrics['accuracy'] * 100:.1f}%", "Correct predictions", "#2563eb")
with c2:
    ui.card("Precision", f"{metrics['precision'] * 100:.1f}%", "Flagged and truly weak", "#7c3aed")
with c3:
    ui.card("Recall", f"{metrics['recall'] * 100:.1f}%", "Weak topics that were found", "#059669")
with c4:
    ui.card("F1-score", f"{metrics['f1_score'] * 100:.1f}%", "Precision and recall combined", "#d97706")

d1, d2, d3 = st.columns(3)
with d1:
    ui.card("Training accuracy", f"{metrics['train_accuracy'] * 100:.1f}%", "Overfitting check", "#64748b")
with d2:
    ui.card("5-fold CV F1", f"{metrics['cv_f1_mean'] * 100:.1f}%", f"± {metrics['cv_f1_std'] * 100:.1f} (training data only)", "#64748b")
with d3:
    ui.card("Rows (train / test)", f"{metrics['train_rows']} / {metrics['test_rows']}",
            "80% / 20% stratified split", "#64748b")

gap = metrics["train_accuracy"] - metrics["accuracy"]
if gap > 0.10:
    st.warning(f"Training accuracy is {gap * 100:.1f} points above test accuracy: possible overfitting.")
else:
    st.success(f"Training and test accuracy are close (gap {gap * 100:.1f} points), so there is no strong sign of overfitting.")

left, right = st.columns(2)
with left:
    st.subheader("Confusion matrix")
    fig = px.imshow(metrics["confusion_matrix"], text_auto=True,
                    x=["Predicted On Track", "Predicted Needs Practice"],
                    y=["Actual On Track", "Actual Needs Practice"],
                    color_continuous_scale="Blues")
    fig.update_layout(coloraxis_showscale=False)
    ui.show_plot(fig)
    st.caption("Diagonal = correct. Top-right = false alarms. Bottom-left = missed weak topics.")
with right:
    st.subheader("Feature importance")
    importance = pd.DataFrame({
        "Feature": [FEATURE_LABELS[k] for k in metrics["feature_importance"]],
        "Importance": list(metrics["feature_importance"].values()),
    }).sort_values("Importance")
    fig = px.bar(importance, x="Importance", y="Feature", orientation="h")
    fig.update_traces(marker_color="#2563eb")
    ui.show_plot(fig)
    st.caption("How much each input mattered to the model overall (for the synthetic data).")

st.subheader("Classification report")
report = metrics["classification_report"]
rows = []
for name in ["On Track", "Needs Practice", "macro avg", "weighted avg"]:
    r = report[name]
    rows.append({"Class": name, "Precision": round(r["precision"], 3),
                 "Recall": round(r["recall"], 3), "F1-score": round(r["f1-score"], 3),
                 "Support": int(r["support"])})
st.dataframe(pd.DataFrame(rows), hide_index=True)

# ----------------------------------------------------------------------
st.subheader("Try the model with hypothetical values")
st.caption("These sliders are NOT saved and are not your data. They only show how the model reacts.")
if bundle is None:
    st.error("The model could not be loaded.")
else:
    s1, s2, s3, s4 = st.columns(4)
    previous = s1.slider("Previous score (%)", 0, 100, 50)
    latest = s2.slider("Latest score (%)", 0, 100, 45)
    attempts = s3.slider("Number of attempts", 1, 15, 3)
    days = s4.slider("Days since last practice", 0, 60, 10)
    result = predict_topic(bundle, previous_score=float(previous), latest_score=float(latest),
                           num_attempts=int(attempts), days_since_last_practice=int(days))
    css = "badge-high" if result["label"] == "Needs Practice" else "badge-low"
    st.markdown(f"Prediction: {ui.badge(result['label'], css)} &nbsp; "
                f"P(Needs Practice) = **{result['probability_needs_practice']:.2f}**",
                unsafe_allow_html=True)
    st.dataframe(pd.DataFrame(result["factors"]).rename(
        columns={"feature": "Feature", "value": "Value", "effect": "Effect on probability",
                 "meaning": "Meaning"}), hide_index=True)

# ----------------------------------------------------------------------
st.subheader("Model prediction vs rules vs measured performance")
st.table({
    "Type": ["Measured performance", "Model prediction", "Rule-based advice"],
    "Source": ["Your saved quiz results", "Random Forest (synthetic training data)", "Fixed if-then rules with points"],
    "Where you see it": ["Study Planner, Dashboard, Analytics", "Study Planner, Quiz results, this page", "Study Planner"],
})

with st.expander("Dataset preview (synthetic)"):
    if DATA_PATH.exists():
        st.dataframe(pd.read_csv(DATA_PATH).head(20), hide_index=True)
        st.caption(f"Class counts: {metrics['class_counts_all']}")

with st.expander("Limitations"):
    st.markdown(
        "- Trained on synthetic data. Real students may behave differently.\n"
        "- Only four input features are used.\n"
        "- The explanation method changes one feature at a time, so it is approximate.\n"
        "- Some quizzes have only 2 to 6 questions, so scores are coarse."
    )

if st.button("🔄 Retrain model"):
    with st.spinner("Training..."):
        train_and_save()
    st.success("Model retrained with the same fixed random seed.")
    st.rerun()